// One-component JPEG container with a frame, scan and non-empty entropy data.
export const jpeg = Uint8Array.from([
  0xff, 0xd8, 0xff, 0xc0, 0x00, 0x0b, 0x08, 0x00, 0x01, 0x00, 0x01, 0x01, 0x01,
  0x11, 0x00, 0xff, 0xda, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3f, 0x00, 0x01,
  0xff, 0xd9,
])

export const jpegDataUrl = `data:image/jpeg;base64,${btoa(String.fromCharCode(...jpeg))}`
